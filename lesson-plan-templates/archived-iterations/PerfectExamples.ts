const healthPromptMarch = generatePerfectPrompt(
  'Formation personnelle et sociale',
  'Gérer mes émotions',
  12,
  12,
  3
);

const expectedHealthResponse = `
Title: Ma boîte à outils calme - My Calm-Down Toolbox

Learning Goal: Students will identify personal strategies for managing big feelings.

Success Indicators:
• Names 2-3 calming strategies that work for them
• Demonstrates one calming technique
• Creates personal calm-down tool

Vocabulary:
1. respirer (breathe) - Gesture: Hand on belly, breathe in/out - Visual: Balloon inflating/deflating
2. calme (calm) - Gesture: Smooth hands down from head - Visual: Calm water picture
3. fort (strong) - Gesture: Flex arms - Visual: Tree standing strong in wind
4. choix (choice) - Gesture: One hand, then other hand - Visual: Two path arrows
5. mieux (better) - Gesture: Thumbs up - Visual: Smiley face chart

Opening Hook (10 min):
Puppet Pierre is VERY upset - he lost his favorite toy! He's stomping, crying (demonstrate safely). "Comment peut-on aider Pierre?" Students suggest ideas. Pierre tries deep breaths with the class - in through nose (smell flowers), out through mouth (blow out candles). "Je me sens mieux!" Try other strategies students suggest. Pierre thanks class for helping him find ways to feel calme.

Main Learning (27 min):
Creating our Calm-Down Toolboxes! First, explore stations with different calming tools:

Station 1: Breathing cards (flower/candle, snake breath, belly breathing)
Station 2: Movement cards (wall push-ups, stretches, shake it out)
Station 3: Comfort items (stress balls, soft fabric, fidgets)
Station 4: Quiet activities (coloring mandalas, looking books, puzzles)

Partners visit each station (5 min each), trying tools. Use timer for transitions.

Movement break integrated into stations!

After exploring, students choose 2-3 strategies that work for them. Create personal calm-down card:
- Draw or glue pictures of chosen strategies
- Decorate with calming colors
- Add "Je peux..." (I can...) with teacher help

Wrap-up (8 min):
Circle time with calm-down cards. Volunteers share one strategy: "Quand je suis fâché, je peux respirer." Practice favorite class strategy together - vote with thumbs. End with commitment: "Tomorrow when I have big feelings, I will try..." Teacher models first. Students who want to share can, others can share with partner or keep private.

Materials:
• Puppet
• Breathing visual cards (pre-made)
• Movement cards (pre-made)
• Stress balls, fabric squares, fidgets
• Simple coloring sheets
• Cardstock for calm-down cards
• Glue sticks, crayons, markers
• Timer

Assessment:
Observation during station exploration. Look for: trying different strategies, identifying preferences, creating personal tool. Note: This is about finding what works for each child, not "correct" answers.

Support Strategies:
• Partner sensitive students with calm peer
• Allow drawing instead of writing
• Provide pre-made cards to choose from
• Offer to be a student's "practice partner"

Extensions:
• Create calm-down book with multiple strategies
• Teach a calming strategy to younger student

Emotional Safety:
• All participation voluntary - option to observe
• No sharing personal upset experiences required
• Calm corner available if anyone needs break
• Celebrate that everyone has different needs
• Frame as "tools" not "problems to fix"`;

