const mathPromptJanuary = generatePerfectPrompt(
  'Mathématiques',
  'Résoudre des problèmes',
  5,
  10,
  1
);

const expectedMathResponse = `
Title: L'animalerie de classe - Our Classroom Pet Store

Learning Goal: Students will solve addition problems using manipulatives and drawings.

Success Indicators:
• Uses objects to show addition
• Explains solution with "et" (and) and "font" (makes)
• Records addition with pictures

Vocabulary:
1. plus - Gesture: Cross fingers to make + sign - Visual: Big + sign
2. égale (equals) - Gesture: Two flat hands side by side - Visual: = sign
3. ensemble (together) - Gesture: Bring two fists together - Visual: Two groups joining
4. combien (how many) - Gesture: Shrug with palms up - Visual: ? card

Opening Hook (10 min):
Pet store is opening in our class! But oh no - all the animals are mixed up! Show two stuffed dogs and three stuffed cats in separate cages (boxes). "Combien de chiens? Combien de chats?" Now they want to play together - put them ensemble. "Combien d'animaux en tout?" Count together. Practice with toy animals, using new vocabulary with gestures.

Main Learning (27 min):
Pet Store Problems! Partners run a pet store table. Each table has different animals (plastic animals, counting bears as "pets"). 

Teacher demonstrates first problem with whole class: "2 hamsters et 3 hamsters font...?" Students solve with manipulatives.

Partners take turns being store owner and customer:
- Customer rolls two dice
- First die = first group of pets, second die = second group  
- Store owner combines groups and counts total
- Both record with drawings

Movement break (2 min): Animal movements - hop like 3 bunnies, waddle like 2 ducks, then count all movements together!

Continue with story problems: "The pet store has 4 fish. 2 more fish arrive. How many now?" Partners solve and share solutions using "et" and "font."

Wrap-up (8 min):
Gallery walk - partners visit one other table to see their pet math. Come to carpet with whiteboards. Teacher says problem: "3 et 2 font...?" Students draw and solve. Show boards on count of trois. Celebrate different ways to show same answer.

Materials:
• Stuffed animals or plastic animals
• Counting bears as backup "pets"
• Small boxes as "cages"
• Dice
• Paper and crayons
• Individual whiteboards and markers

Assessment:
Observe problem-solving strategies. Look for: accurate counting, use of "et" and "font", different representations (objects, fingers, drawings).

Support Strategies:
• Start with sums to 5 only
• Provide number line as reference
• Count together before independent work
• Use French and English for explanations

Extensions:
• Create own pet store problem for others
• Try subtraction: "5 dogs, 2 go home..."`;

