const expectedScienceResponse = `
Title: Les feuilles tombent! - The Leaves are Falling!

Learning Goal: Students will observe and describe signs of fall using their senses.

Success Indicators:
• Names 2-3 fall changes they can see
• Uses French color words when describing leaves
• Shows curiosity about seasonal changes

Vocabulary:
1. feuille (leaf) - Gesture: Flutter hands down like falling leaves - Visual: Real fall leaves
2. arbre (tree) - Gesture: Arms up like branches - Visual: Photo of school yard tree
3. tomber (to fall) - Gesture: Whoosh hand downward - Visual: Leaves falling picture

Opening Hook (10 min):
Bring in a mystery bag with crunchy fall leaves inside. Let students hear the crunch first - "Qu'est-ce que c'est?" Take out leaves one by one, letting students touch and smell. Practice vocabulary with gestures. Everyone does the "falling leaf dance" - arms up high, slowly twirl down to ground.

Main Learning (28 min):
Nature detectives! Each pair gets a collecting bag and magnifying glass. Go to school yard (or use collected leaves if weather bad). Partners take turns - one finds a leaf, other describes color in French. 

Movement break (2 min): Tree poses - sway in wind, drop leaves.

Back inside, sort leaves at tables. Create leaf rainbow on floor - rouge here, jaune there, brun over there. Count each color group in French. Make leaf rubbings with crayons - gentle circles show leaf patterns.

Wrap-up (7 min):
Sit in circle with leaf collections. Each pair shows favorite leaf. Teacher models: "Voici une feuille rouge!" Partners echo. End with question: "What else changes in fall?" Draw one fall change as exit ticket.

Materials:
• Fall leaves (collected in advance)
• Mystery bag
• Magnifying glasses (6-8)
• Collection bags
• White paper
• Crayons
• Sorting mats

Assessment: 
Observation during outdoor exploration and sorting. Look for: attempts at French color words, careful observation with magnifying glass, engagement with partner.

Support Strategies:
• Pair French-confident with emerging speaker
• Provide color cards for matching if needed
• Allow pointing and gesturing instead of French words initially

Extensions:
• Create leaf pattern (red-yellow-red-yellow)
• Draw and label parts of leaf

Safety:
• Define boundaries for outdoor exploration
• No picking leaves from gardens
• Wash hands after handling leaves
• Check for allergies before activity`;

